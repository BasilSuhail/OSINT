"""Things that are somewhere now (#873).

Presence is the other half of what this console watches, and it is not
evidence. One question separates them:

    Can this be cited later?

Evidence is a claim that something happened: persisted, graded, retained,
audited, and available for a story to point at. Presence is where something
*is, right now* — fetched, drawn, discarded. A military aircraft's position
twenty minutes ago supports no argument and answers no question, which is
exactly why it must not be kept.

Nothing in this package writes a row. It imports no database model, registers
no retention window, declares no audit expectation, and a test enforces the
first of those so the boundary cannot quietly erode.

There is a licence argument for the same discipline. The publisher releases
under ODbL: attribution is required, and share-alike attaches to adapted
databases that are publicly used. A map drawn from live data is a Produced
Work, which needs the notice and nothing more. Storing this data is what would
create the obligation — so the tier that refuses to store is also the tier that
stays clean.
"""
